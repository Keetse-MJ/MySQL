#1.The manager wants to see the 5 largest individual sales, showing the customer, product, city, and amount.

SELECT customer,product,city,amount
FROM sales
ORDER BY amount DESC
LIMIT 5;

#2. Find all sales made by Thabo in Johannesburg.

SELECT*
FROM sales
WHERE customer="Thabo" AND city="Johannesburg";

#3. Which customers have made more than 2 purchases?

SELECT customer,COUNT(amount) AS purchases
FROM sales
GROUP BY customer
HAVING purchases > 2;



#4. Which products have been sold in more than one city?

